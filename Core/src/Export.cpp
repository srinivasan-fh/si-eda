std::string spiceNode(const Schematic& sch, PinRef pin) {
    int n = sch.netOf(pin);
    if (n < 0) return "NC_" + std::to_string(pin.component) + "_" + std::to_string(pin.pin);
    const Net& net = sch.nets()[static_cast<size_t>(n)];
    if (net.isGround) return "0";
    std::string s = net.name;
    for (char& c : s)
        if (!std::isalnum(static_cast<unsigned char>(c)) && c != '_') c = '_';
    return s;
}

std::string spiceSource(const std::string& value) {
    auto spec = SourceSpec::parse(value);
    if (!spec) return "DC 0";
    char buf[160];
    switch (spec->kind) {
        case SourceSpec::Kind::DC: std::snprintf(buf, sizeof buf, "DC %g", spec->dc); break;
        case SourceSpec::Kind::Sine:
            std::snprintf(buf, sizeof buf, "SIN(%g %g %g)", spec->offset, spec->amplitude, spec->frequency);
            break;
        case SourceSpec::Kind::Pulse:
            std::snprintf(buf, sizeof buf, "PULSE(%g %g 0 1n 1n %g %g)", spec->v1, spec->v2, spec->period * spec->duty,
                          spec->period);
            break;
    }
    return buf;
}

std::string mm(double v) {
    char b[32];
    std::snprintf(b, sizeof b, "%.4f", v);
    return b;
}

std::string footprintLabel(const Component& c) {
    const FootprintDef* fp = Library::instance().footprint(c.def().footprint);
    if (!fp) return c.def().footprint;
    return fp->label.empty() ? fp->name : fp->label;
}

std::string csvEscape(const std::string& s) {
    if (s.find_first_of(",\"\n") == std::string::npos) return s;
    std::string out = "\"";
    for (char c : s) out += c == '"' ? std::string("\"\"") : std::string(1, c);
    return out + "\"";
}
