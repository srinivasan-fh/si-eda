#!/usr/bin/env python3
"""Writes Core/src/ExampleProjects.cpp: the built-in example projects too large to build in code (MCP
project_load_example), embedded from examples/ as raw string literals. Both the CMake build and the generated Xcode
project compile Core/src/*.cpp, so the file is checked in: run this again after changing an example project, don't
edit the output by hand. --check exits 1 when the file is stale."""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXAMPLES = [("smpsExampleJson", "examples/smps-230vac-5-48v/smps_230vac.siedaproj"),
            ("smps1LayerExampleJson", "examples/smps-230vac-5-48v-1layer/smps_230vac_1layer.siedaproj")]
OUT = ROOT / "Core/src/ExampleProjects.cpp"
CHUNK = 8000  # characters per literal (one long literal would pass the compilers' -Woverlength-strings limit)


def render():
    out = ["// Generated by tools/embed_examples.py from examples/: do not edit.", "#include <string>", ""]
    for name, path in EXAMPLES:
        text = (ROOT / path).read_text(encoding="utf-8")
        assert ')sieda"' not in text
        out.append(f"// {path}")
        out.append(f"std::string {name}();")
        out.append(f"std::string {name}() {{")
        out.append("    static const char* const parts[] = {")
        out += [f'        R"sieda({text[i:i + CHUNK]})sieda",' for i in range(0, len(text), CHUNK)]
        out.append("    };")
        out.append("    std::string json;")
        out.append("    for (const char* part : parts) json += part;")
        out.append("    return json;")
        out.append("}")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
